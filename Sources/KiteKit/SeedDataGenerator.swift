import Foundation

public enum SeedDataGenerator {
    private static let sampleNames = ["Алексей Смирнов", "Елена Соколова", "Михаил Иванов", "Дарья Кузнецова", "Артем Васильев", "Анна Попова"]
    private static let sampleEmails = ["alex@example.com", "elena@example.com", "mikhail@example.com", "daria@example.com", "artem@example.com", "anna@example.com"]
    private static let sampleProjectTitles = ["Kite Cockpit", "Habit Tracker", "Local AI Studio", "Finance Hub", "Minimal Reader", "Agentic Flow"]

    public static func generateMockRows(for entity: SchemaEntity, count: Int = 3) -> [[String: String]] {
        var rows: [[String: String]] = []

        for i in 0..<count {
            var row: [String: String] = [:]
            for field in entity.fields {
                switch field.type {
                case .uuid:
                    row[field.name] = "\(entity.name.lowercased())_\(i + 1)"
                case .string:
                    if field.name.lowercased().contains("email") {
                        row[field.name] = sampleEmails[i % sampleEmails.count]
                    } else if field.name.lowercased().contains("name") {
                        row[field.name] = sampleNames[i % sampleNames.count]
                    } else if field.name.lowercased().contains("title") {
                        row[field.name] = sampleProjectTitles[i % sampleProjectTitles.count]
                    } else {
                        row[field.name] = "\(field.name)_\(i + 1)"
                    }
                case .int:
                    row[field.name] = "\((i + 1) * 10)"
                case .boolean:
                    row[field.name] = i % 2 == 0 ? "true" : "false"
                case .dateTime:
                    row[field.name] = "2026-11-06T1\(i):00:00Z"
                case .relation:
                    let target = field.relationTarget?.lowercased() ?? "user"
                    row[field.name] = "\(target)_1"
                }
            }
            rows.append(row)
        }

        return rows
    }

    public static func generateSQL(entities: [SchemaEntity], count: Int = 3) -> String {
        var lines: [String] = [
            "-- Realistic Seed Data generated by Kite",
            ""
        ]

        for entity in entities {
            let table = entity.name.lowercased() + "s"
            let rows = generateMockRows(for: entity, count: count)
            for row in rows {
                let cols = row.keys.sorted().joined(separator: ", ")
                let vals = row.keys.sorted().map { k -> String in
                    let val = row[k] ?? ""
                    if val == "true" || val == "false" || Int(val) != nil {
                        return val
                    }
                    return "'\(val)'"
                }.joined(separator: ", ")
                lines.append("INSERT INTO \(table) (\(cols)) VALUES (\(vals));")
            }
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    public static func generateTypeScript(entities: [SchemaEntity], count: Int = 3) -> String {
        var lines: [String] = [
            "// Realistic Prisma / Drizzle Seed Script generated by Kite",
            "import { PrismaClient } from '@prisma/client';",
            "const prisma = new PrismaClient();",
            "",
            "async function main() {"
        ]

        for entity in entities {
            let modelName = entity.name.prefix(1).lowercased() + entity.name.dropFirst()
            let rows = generateMockRows(for: entity, count: count)
            lines.append("  await prisma.\(modelName).createMany({")
            lines.append("    data: [")
            for row in rows {
                let pairs = row.map { k, v in
                    if v == "true" || v == "false" || Int(v) != nil {
                        return "      \(k): \(v)"
                    }
                    return "      \(k): \"\(v)\""
                }.joined(separator: ",\n")
                lines.append("      {\n\(pairs)\n      },")
            }
            lines.append("    ]")
            lines.append("  });\n")
        }

        lines.append("  console.log('Seed completed successfully');")
        lines.append("}")
        lines.append("\nmain().finally(() => prisma.$disconnect());")

        return lines.joined(separator: "\n")
    }

    public static func generateJSON(entities: [SchemaEntity], count: Int = 3) -> String {
        var dict: [String: [[String: String]]] = [:]
        for entity in entities {
            let key = entity.name.lowercased() + "s"
            dict[key] = generateMockRows(for: entity, count: count)
        }

        if let data = try? JSONSerialization.data(withJSONObject: dict, options: [.prettyPrinted]),
           let str = String(data: data, encoding: .utf8) {
            return str
        }
        return "{}"
    }
}

import Foundation

public struct UIComponentContract: Identifiable, Sendable, Equatable {
    public var id: String { name }
    public var name: String
    public var description: String
    public var propsTypeScript: String
    public var requiredStates: [String]
    public var a11yRole: String

    public init(name: String, description: String, propsTypeScript: String, requiredStates: [String], a11yRole: String) {
        self.name = name
        self.description = description
        self.propsTypeScript = propsTypeScript
        self.requiredStates = requiredStates
        self.a11yRole = a11yRole
    }
}

public enum ComponentContractMatrix {
    public static var starterPack: [UIComponentContract] {
        [
            UIComponentContract(
                name: "HeaderBar",
                description: "Верхняя панель навигации со статусом и действиями",
                propsTypeScript: "interface HeaderBarProps {\n  title: string;\n  status?: 'active' | 'syncing' | 'offline';\n  onActionClick: () => void;\n}",
                requiredStates: ["default", "syncing"],
                a11yRole: "banner"
            ),
            UIComponentContract(
                name: "StatCard",
                description: "Информационная карточка метрики с трендом",
                propsTypeScript: "interface StatCardProps {\n  label: string;\n  value: string | number;\n  trend?: { percent: number; isPositive: boolean };\n  isLoading?: boolean;\n}",
                requiredStates: ["idle", "loading"],
                a11yRole: "region"
            ),
            UIComponentContract(
                name: "DataTable",
                description: "Интерактивная таблица сущностей с сортировкой и фильтром",
                propsTypeScript: "interface DataTableProps<T> {\n  items: T[];\n  isLoading: boolean;\n  isEmpty: boolean;\n  onRowSelect: (item: T) => void;\n}",
                requiredStates: ["loading", "empty", "populated", "error"],
                a11yRole: "table"
            ),
            UIComponentContract(
                name: "ActionModal",
                description: "Диалоговое окно подтверждения деструктивного действия",
                propsTypeScript: "interface ActionModalProps {\n  isOpen: boolean;\n  title: string;\n  confirmLabel: string;\n  onConfirm: () => Promise<void>;\n  onCancel: () => void;\n}",
                requiredStates: ["idle", "submitting"],
                a11yRole: "dialog"
            )
        ]
    }

    public static func generateTypeScriptDefinitions(components: [UIComponentContract]) -> String {
        var lines: [String] = [
            "// UI Component Contracts & Props Matrix generated by Kite",
            "// Strict interfaces for Google DeepMind Antigravity implementation",
            ""
        ]

        for comp in components {
            lines.append("/**")
            lines.append(" * \(comp.name): \(comp.description)")
            lines.append(" * Required States: \(comp.requiredStates.joined(separator: ", "))")
            lines.append(" * ARIA Role: \(comp.a11yRole)")
            lines.append(" */")
            lines.append(comp.propsTypeScript)
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    public static func generatePromptDirective(components: [UIComponentContract]) -> String {
        var lines: [String] = [
            "[ANTIGRAVITY COMPONENT CONTRACT DIRECTIVE]",
            "When generating UI components, adhere strictly to these prop contracts:",
            ""
        ]

        for comp in components {
            lines.append("- \(comp.name): Must handle states [\(comp.requiredStates.joined(separator: ", "))] with role=\"\(comp.a11yRole)\"")
        }

        lines.append("")
        lines.append("Do not introduce arbitrary prop names like `handleClick` if `onActionClick` is specified.")
        return lines.joined(separator: "\n")
    }
}

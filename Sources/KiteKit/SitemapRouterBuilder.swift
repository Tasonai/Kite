import Foundation

public struct AppScreenRoute: Identifiable, Sendable, Codable, Equatable {
    public var id: UUID
    public var path: String
    public var title: String
    public var presentation: ScreenPresentation
    public var description: String

    public enum ScreenPresentation: String, Sendable, CaseIterable, Codable {
        case push = "Push в стек"
        case modal = "Модальное окно (Sheet)"
        case drawer = "Боковая шторка (Drawer)"
        case tab = "Вкладка навигации (Tab)"
    }

    public init(
        id: UUID = UUID(),
        path: String,
        title: String,
        presentation: ScreenPresentation = .push,
        description: String = ""
    ) {
        self.id = id
        self.path = path
        self.title = title
        self.presentation = presentation
        self.description = description
    }
}

public enum SitemapRouterBuilder {
    public static var starterSitemap: [AppScreenRoute] {
        [
            AppScreenRoute(path: "/", title: "Лендинг / Главная", presentation: .tab, description: "Витрина продукта и призыв к действию"),
            AppScreenRoute(path: "/auth/login", title: "Авторизация", presentation: .modal, description: "Вход по email и magic link"),
            AppScreenRoute(path: "/dashboard", title: "Главная консоль", presentation: .tab, description: "Сводка метрик и активные проекты"),
            AppScreenRoute(path: "/projects/:id", title: "Детали проекта", presentation: .push, description: "Холст архитектуры и параметры"),
            AppScreenRoute(path: "/settings", title: "Настройки профиля", presentation: .drawer, description: "API ключи, тема и экспорт")
        ]
    }

    public static func generateNextJsAppRouter(routes: [AppScreenRoute]) -> String {
        var lines: [String] = [
            "// Next.js 15 App Router Structure generated by Kite",
            "// File Tree:",
        ]

        for r in routes {
            let clean = r.path == "/" ? "page.tsx" : "\(r.path.replacingOccurrences(of: "^/", with: "", options: .regularExpression))/page.tsx"
            lines.append("// - app/\(clean) -> \(r.title) (\(r.presentation.rawValue))")
        }

        lines.append("\n// Example router navigation manifest:")
        lines.append("export const APP_ROUTES = [")
        for r in routes {
            lines.append("  { path: '\(r.path)', title: '\(r.title)', presentation: '\(r.presentation.rawValue)' },")
        }
        lines.append("] as const;")

        return lines.joined(separator: "\n")
    }

    public static func generateSwiftUIRouter(routes: [AppScreenRoute]) -> String {
        var lines: [String] = [
            "import SwiftUI",
            "",
            "// SwiftUI Type-Safe NavigationStack Router from Kite",
            "public enum AppRoute: Hashable {",
        ]

        for r in routes {
            let enumCase = routeEnumCase(path: r.path)
            lines.append("    case \(enumCase) // \(r.title)")
        }

        lines.append("}\n")
        lines.append("@Observable\npublic final class AppNavigationStore {")
        lines.append("    public var path = NavigationPath()")
        lines.append("    public func navigate(to route: AppRoute) { path.append(route) }")
        lines.append("    public func pop() { if !path.isEmpty { path.removeLast() } }")
        lines.append("}")

        return lines.joined(separator: "\n")
    }

    private static func routeEnumCase(path: String) -> String {
        if path == "/" { return "home" }
        let clean = path.replacingOccurrences(of: ":", with: "")
            .components(separatedBy: "/")
            .filter { !$0.isEmpty }
            .map { $0.prefix(1).uppercased() + $0.dropFirst() }
            .joined()
        return clean.prefix(1).lowercased() + clean.dropFirst()
    }
}

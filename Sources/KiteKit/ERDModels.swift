public struct ERDColumn: Identifiable, Sendable, Equatable, Codable {
    public var id: String { name }
    public var name: String
    public var type: String
    public var isPrimaryKey: Bool
    public var isNullable: Bool
    public var isForeignKey: Bool
    public var referencesTable: String?
    public var referencesColumn: String?

    public init(
        name: String,
        type: String,
        isPrimaryKey: Bool = false,
        isNullable: Bool = false,
        isForeignKey: Bool = false,
        referencesTable: String? = nil,
        referencesColumn: String? = nil
    ) {
        self.name = name
        self.type = type
        self.isPrimaryKey = isPrimaryKey
        self.isNullable = isNullable
        self.isForeignKey = isForeignKey
        self.referencesTable = referencesTable
        self.referencesColumn = referencesColumn
    }
}

public struct ERDTable: Identifiable, Sendable, Equatable, Codable {
    public var id: String { name }
    public var name: String
    public var columns: [ERDColumn]
    public var x: Double
    public var y: Double

    public init(name: String, columns: [ERDColumn], x: Double = 100, y: Double = 100) {
        self.name = name
        self.columns = columns
        self.x = x
        self.y = y
    }
}

public struct ERDRelationship: Identifiable, Sendable, Equatable, Codable {
    public var id: String { "\(fromTable).\(fromColumn)->\(toTable).\(toColumn)" }
    public var fromTable: String
    public var fromColumn: String
    public var toTable: String
    public var toColumn: String
    public var kind: String // 1:1, 1:N, N:M

    public init(fromTable: String, fromColumn: String, toTable: String, toColumn: String, kind: String = "1:N") {
        self.fromTable = fromTable
        self.fromColumn = fromColumn
        self.toTable = toTable
        self.toColumn = toColumn
        self.kind = kind
    }
}

public struct ERDSchema: Sendable, Equatable, Codable {
    public var tables: [ERDTable]
    public var relationships: [ERDRelationship]

    public init(tables: [ERDTable], relationships: [ERDRelationship]) {
        self.tables = tables
        self.relationships = relationships
    }
}


    public static func generatePostgresSql(schema: ERDSchema) -> String {
        var lines: [String] = []
        lines.append("-- PostgreSQL Relational Database Schema DDL")
        lines.append("-- Generated by Kite ERD Schema Studio (Antigravity Standard)")
        lines.append("CREATE EXTENSION IF NOT EXISTS \"uuid-ossp\";")
        lines.append("")

        for t in schema.tables {
            lines.append("CREATE TABLE IF NOT EXISTS \(t.name) (")
            var colDefs: [String] = []
            for col in t.columns {
                var def = "    \(col.name) \(col.type)"
                if col.isPrimaryKey {
                    def += " PRIMARY KEY"
                } else if !col.isNullable {
                    def += " NOT NULL"
                }
                colDefs.append(def)
            }

            for rel in schema.relationships.filter({ $0.fromTable == t.name }) {
                let fkName = "fk_\(t.name)_\(rel.fromColumn)"
                colDefs.append("    CONSTRAINT \(fkName) FOREIGN KEY (\(rel.fromColumn)) REFERENCES \(rel.toTable)(\(rel.toColumn)) ON DELETE CASCADE")
            }

            lines.append(colDefs.joined(separator: ",\n"))
            lines.append(");")
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    public static func generatePrismaSchema(schema: ERDSchema) -> String {
        var lines: [String] = []
        lines.append("// Prisma Data Modeling Schema")
        lines.append("// Generated by Kite ERD Schema Studio")
        lines.append("datasource db {")
        lines.append("  provider = \"postgresql\"")
        lines.append("  url      = env(\"DATABASE_URL\")")
        lines.append("}")
        lines.append("")
        lines.append("generator client {")
        lines.append("  provider = \"prisma-client-js\"")
        lines.append("}")
        lines.append("")

        for t in schema.tables {
            let modelName = t.name.prefix(1).uppercased() + t.name.dropFirst()
            lines.append("model \(modelName) {")
            for col in t.columns {
                let pType: String
                switch col.type.uppercased() {
                case let s where s.contains("UUID"): pType = "String"
                case let s where s.contains("VARCHAR") || s.contains("TEXT"): pType = "String"
                case let s where s.contains("INT"): pType = "Int"
                case let s where s.contains("BOOL"): pType = "Boolean"
                case let s where s.contains("TIME") || s.contains("DATE"): pType = "DateTime"
                default: pType = "String"
                }

                var line = "  \(col.name) \(pType)"
                if col.isPrimaryKey {
                    line += " @id @default(uuid())"
                }
                lines.append(line)
            }
            lines.append("  @@map(\"\(t.name)\")")
            lines.append("}")
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    public static func generateErdMarkdown(title: String, schema: ERDSchema) -> String {
        var lines: [String] = []
        lines.append("# ENTITY-RELATIONSHIP DIAGRAM & RELATIONAL SCHEMA: \(title.uppercased())")
        lines.append("")
        lines.append("> Synthesized by Kite High-Density Canvas Engine following Antigravity Standard.")
        lines.append("")
        lines.append("## 1. Tables & Columns Matrix")
        lines.append("")
        lines.append("| Table | Column | Type | Constraints | References |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")

        for t in schema.tables {
            for col in t.columns {
                var constraints: [String] = []
                if col.isPrimaryKey { constraints.append("PK") }
                if !col.isNullable { constraints.append("NOT NULL") }
                let cStr = constraints.isEmpty ? "None" : constraints.joined(separator: ", ")
                let refStr = col.referencesTable != nil ? "\(col.referencesTable!).\(col.referencesColumn!)" : "-"
                lines.append("| `\(t.name)` | `\(col.name)` | `\(col.type)` | `\(cStr)` | `\(refStr)` |")
            }
        }

        lines.append("")
        lines.append("## 2. Mermaid Entity-Relationship Diagram")
        lines.append("```mermaid")
        lines.append("erDiagram")
        for rel in schema.relationships {
            lines.append("    \(rel.toTable) ||--o{ \(rel.fromTable) : \"\(rel.fromColumn)\"")
        }
        for t in schema.tables {
            lines.append("    \(t.name) {")
            for c in t.columns {
                lines.append("        \(c.type) \(c.name)")
            }
            lines.append("    }")
        }
        lines.append("```")
        lines.append("")
        lines.append("## 3. PostgreSQL DDL Schema")
        lines.append("```sql")
        lines.append(generatePostgresSql(schema: schema))
        lines.append("```")
        lines.append("")
        return lines.joined(separator: "\n")
    }
